"""Derive the standard-font kerning pairs in crates/vellum-engine/src/kerning.rs.

A composed document lays a standard font out as pdfkit does: each glyph's
advance is its AFM width plus the pair it makes with the next. The pairs have
to be Adobe's, those pdfkit applies: the URW clones the widths come from kern
differently. pdfkit ships Adobe's Core 14 AFM files in `js/data/`.

Run it only to regenerate the table; the build does not need it. It wants
those AFM files and fonttools, for the Adobe Glyph List.

    python3 scripts/generate-kerning.py node_modules/pdfkit/js/data \\
        crates/vellum-engine/src/kerning.rs
"""
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
spec = importlib.util.spec_from_file_location("metrics", HERE / "generate-metrics.py")
metrics = importlib.util.module_from_spec(spec)
spec.loader.exec_module(metrics)

# Constant, AFM file. The obliques kern as their uprights, Courier not at all.
FONTS = [
    ("HELVETICA", "Helvetica"),
    ("HELVETICA_BOLD", "Helvetica-Bold"),
    ("TIMES_ROMAN", "Times-Roman"),
    ("TIMES_BOLD", "Times-Bold"),
    ("TIMES_ITALIC", "Times-Italic"),
    ("TIMES_BOLD_ITALIC", "Times-BoldItalic"),
]

HEADER = """//! Kerning of the standard fonts.
//!
//! pdfkit lays a standard font out with the AFM's kerning pairs: the advance
//! of each glyph is its width plus the pair it makes with the next one. The
//! stand-in drawn in its place has kerning of its own, close but not the
//! same, and a line measured with it breaks where pdfkit's does not.
//!
//! The pairs are those of Adobe's Core 14 AFM files, keeping the ones whose
//! two glyphs WinAnsi can encode, indexed by WinAnsi byte and sorted for a
//! binary search: `(left, right, thousandths of an em)`. The obliques kern as
//! their uprights do, and Courier, being monospace, not at all. Generated by
//! `scripts/generate-kerning.py`.
//!
//! Helvetica: Copyright (c) 1985, 1987, 1989, 1990, 1997 Adobe Systems
//! Incorporated. All Rights Reserved. Helvetica is a trademark of
//! Linotype-Hell AG and/or its subsidiaries.
//! Times: Copyright (c) 1985, 1987, 1989, 1990, 1993, 1997 Adobe Systems
//! Incorporated. All Rights Reserved. Times is a trademark of Linotype-Hell
//! AG and/or its subsidiaries.
//! The AFM files may be used, copied and distributed for any purpose; this
//! table is derived from them, reduced to the WinAnsi pairs.
"""


def pairs_of(path):
    """(left glyph, right glyph) -> amount, in 1/1000 of an em."""
    pairs = {}
    for line in path.read_text(encoding="latin-1").splitlines():
        match = re.match(r"KPX\s+(\S+)\s+(\S+)\s+(-?\d+)", line)
        if match:
            pairs[(match.group(1), match.group(2))] = int(match.group(3))
    return pairs


def main():
    afm, out = Path(sys.argv[1]), Path(sys.argv[2])
    names = metrics.win_ansi_names()
    chunks = [HEADER]
    for constant, font in FONTS:
        pairs = pairs_of(afm / f"{font}.afm")
        table = sorted(
            (left, right, pairs[(names[left], names[right])])
            for left in names
            for right in names
            if (names[left], names[right]) in pairs
        )
        # Spot checks against the published Adobe pairs.
        if font == "Helvetica":
            assert (0x41, 0x56, -70) in table, "A V"
            assert (0x76, 0x61, -25) in table, "v a"
        chunks.append(
            f"\n/// {font}, {len(table)} pairs.\n#[rustfmt::skip]\n"
            f"pub(crate) const {constant}: &[(u8, u8, i16)] = &[\n"
        )
        items = [f"(0x{left:02X}, 0x{right:02X}, {amount})" for left, right, amount in table]
        for start in range(0, len(items), 5):
            chunks.append("    " + ", ".join(items[start : start + 5]) + ",\n")
        chunks.append("];\n")
        print(f"{font}: {len(table)} pairs")
    out.write_text("".join(chunks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
